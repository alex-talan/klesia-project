#!/usr/bin/env python3
"""Validate contracts/openapi.yaml and, optionally, compare it with the OpenAPI
document generated by klesia-api. Read-only: this script never writes any file.

Usage (from the workspace root):
  python .claude/skills/check-contract/scripts/validate_contract.py
  python .claude/skills/check-contract/scripts/validate_contract.py --actual api-openapi.json [--all]
  python .claude/skills/check-contract/scripts/validate_contract.py --model klesia_webapp/src/models/demand.ts

Requires: pyyaml, jsonschema. Exit code 1 when at least one ERROR is reported.
"""
import argparse, json, re, sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("pyyaml is required (pip install pyyaml)")
try:
    from jsonschema import FormatChecker
    try:
        from jsonschema import Draft202012Validator as Validator
    except ImportError:  # older jsonschema
        from jsonschema import Draft7Validator as Validator
except ImportError:
    sys.exit("jsonschema is required (pip install jsonschema)")

GK_PATTERN = r"^GK[0-9]{6}-[0-9]{9}$"          # one rule, shared by the DB check and both apps
STATUSES = {"sprint-1", "adopted"}              # x-implementation-status values
SNAKE = re.compile(r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$")
CAMEL_EXCEPTIONS = {"NegotiateResponse", "ProblemDetails"}   # SignalR protocol / RFC 9457 names
METHODS = {"get", "post", "put", "patch", "delete", "head", "options"}

findings = []
def err(msg):  findings.append(("ERROR", msg))
def warn(msg): findings.append(("WARN", msg))

def load(path):
    text = Path(path).read_text(encoding="utf-8")
    return json.loads(text) if str(path).lower().endswith(".json") else yaml.safe_load(text)

def resolve_ref(doc, ref):
    cur = doc
    for part in ref[2:].split("/"):
        part = part.replace("~1", "/").replace("~0", "~")
        if not isinstance(cur, dict) or part not in cur:
            return None
        cur = cur[part]
    return cur

def deref(doc, node, depth=0):
    """Return node with every local $ref expanded (depth-limited for recursion)."""
    if depth > 12:
        return {}
    if isinstance(node, dict):
        if "$ref" in node and isinstance(node["$ref"], str) and node["$ref"].startswith("#/"):
            target = resolve_ref(doc, node["$ref"])
            return deref(doc, target, depth + 1) if target is not None else {}
        return {k: deref(doc, v, depth) for k, v in node.items()}
    if isinstance(node, list):
        return [deref(doc, v, depth) for v in node]
    return node

def operations(doc):
    for path, item in (doc.get("paths") or {}).items():
        for method, op in item.items():
            if method in METHODS and isinstance(op, dict):
                yield path, method, op

# ----------------------------------------------------------------- contract checks
def check_contract(doc):
    if not str(doc.get("openapi", "")).startswith("3.1"):
        err(f"openapi must be 3.1.x (found {doc.get('openapi')!r})")

    def walk(o, where="#"):
        if isinstance(o, dict):
            for k, v in o.items():
                if k == "$ref":
                    if not isinstance(v, str) or not v.startswith("#/"):
                        warn(f"{where}: non-local $ref {v!r} not checked")
                    elif resolve_ref(doc, v) is None:
                        err(f"{where}: unresolved $ref {v}")
                else:
                    walk(v, f"{where}/{k}")
        elif isinstance(o, list):
            for i, v in enumerate(o):
                walk(v, f"{where}/{i}")
    walk(doc)

    ids = {}
    scopes = (((doc.get("components", {}).get("securitySchemes", {}) or {}).get("entraOAuth2", {}) or {})
              .get("flows", {}).get("authorizationCode", {}).get("scopes", {}))
    if "access_as_user" not in scopes:
        err("security scheme entraOAuth2 must define the scope access_as_user")
    if not doc.get("security"):
        err("a global security requirement is required (every route is protected by default)")
    for s in doc.get("servers", []):
        if str(s.get("url", "")).rstrip("/").endswith("/api/v1"):
            err(f"server url {s['url']} must not include /api/v1 (paths carry it)")

    for path, method, op in operations(doc):
        label = f"{method.upper()} {path}"
        if not (path == "/health" or path.startswith("/api/v1/")):
            err(f"{label}: routes must be /health or under /api/v1/")
        oid = op.get("operationId")
        if not oid:
            err(f"{label}: operationId missing")
        elif oid in ids:
            err(f"{label}: operationId {oid!r} duplicates {ids[oid]}")
        else:
            ids[oid] = label
        if op.get("x-implementation-status") not in STATUSES:
            err(f"{label}: x-implementation-status must be one of {sorted(STATUSES)}")
        if op.get("security") == [] and path != "/health":
            err(f"{label}: only /health may be anonymous")
        responses = op.get("responses") or {}
        if path != "/health":
            for code in ("401", "403", "500"):
                if code not in responses:
                    err(f"{label}: response {code} missing")
        for code, resp in responses.items():
            resp = deref(doc, resp)
            if path != "/health" and code.isdigit() and int(code) >= 400:
                if "application/problem+json" not in (resp.get("content") or {}):
                    err(f"{label} {code}: error responses must be application/problem+json")
            for ctype, media in (resp.get("content") or {}).items():
                examples = []
                if "example" in media: examples.append(("example", media["example"]))
                for name, ex in (media.get("examples") or {}).items():
                    if isinstance(ex, dict) and "value" in ex: examples.append((name, ex["value"]))
                for name, value in examples:
                    schema = deref(doc, media.get("schema", {}))
                    for e in Validator(schema, format_checker=FormatChecker()).iter_errors(value):
                        err(f"{label} {code} example {name!r} violates its schema: {e.message}")

    for name, schema in (doc.get("components", {}).get("schemas") or {}).items():
        props = schema.get("properties") or {}
        for req in schema.get("required", []) or []:
            if req not in props:
                err(f"schema {name}: required property {req!r} is not declared")
        if name not in CAMEL_EXCEPTIONS:
            for p in props:
                if not SNAKE.match(p):
                    err(f"schema {name}: property {p!r} must be snake_case")
        if "gk_number" in props and props["gk_number"].get("pattern") != GK_PATTERN:
            err(f"schema {name}: gk_number pattern must be {GK_PATTERN}")
        try:
            Validator.check_schema(deref(doc, schema))
        except Exception as e:  # noqa: BLE001
            err(f"schema {name} is not a valid JSON Schema: {getattr(e, 'message', e)}")

# ----------------------------------------------------------------- contract vs implementation
def shape(doc, schema, depth=0):
    """Normalized structure used to compare two schemas (names, requiredness, types, enums)."""
    s = deref(doc, schema)
    if depth > 6 or not isinstance(s, dict):
        return "?"
    t = s.get("type")
    if isinstance(t, list):
        t = sorted(x for x in t if x != "null")
        t = t[0] if len(t) == 1 else t
    if "properties" in s or t == "object":
        return {"object": {k: shape(doc, v, depth + 1) for k, v in (s.get("properties") or {}).items()},
                "required": sorted(s.get("required") or [])}
    if t == "array":
        return {"array": shape(doc, s.get("items", {}), depth + 1)}
    if "enum" in s:
        return {"enum": sorted(map(str, s["enum"]))}
    return t or "?"

def diff_shape(a, b, where, out):
    if isinstance(a, dict) and isinstance(b, dict):
        if "object" in a and "object" in b:
            for k in sorted(set(a["object"]) | set(b["object"])):
                if k not in b["object"]: out.append(f"{where}.{k}: in contract, missing in implementation")
                elif k not in a["object"]: out.append(f"{where}.{k}: in implementation, not in contract")
                else: diff_shape(a["object"][k], b["object"][k], f"{where}.{k}", out)
            if a["required"] != b["required"]:
                out.append(f"{where}: required differs (contract {a['required']}, implementation {b['required']})")
            return
        if "array" in a and "array" in b:
            return diff_shape(a["array"], b["array"], where + "[]", out)
    if a != b and "?" not in (a, b):
        out.append(f"{where}: contract {a} vs implementation {b}")

def check_actual(contract, actual, include_all):
    actual_paths = {p.rstrip("/") or "/": item for p, item in (actual.get("paths") or {}).items()}
    contract_paths = {p.rstrip("/") or "/" for p in contract.get("paths", {})}
    for path, method, op in operations(contract):
        label = f"{method.upper()} {path}"
        if op.get("x-implementation-status") != "sprint-1" and not include_all:
            continue
        item = actual_paths.get(path)
        if item is None or method not in item:
            err(f"{label}: not found in the implementation's OpenAPI document")
            continue
        aop = item[method]
        c_codes, a_codes = set(op["responses"]), set((aop.get("responses") or {}))
        for c in sorted(c_codes - a_codes): warn(f"{label}: status {c} in contract but not declared by the implementation")
        for c in sorted(a_codes - c_codes - {"default"}): err(f"{label}: status {c} declared by the implementation but not in the contract")
        for code in sorted(c_codes & a_codes):
            if not (code.isdigit() and code.startswith("2")):
                continue
            def body(o):
                resp = deref(contract if o is op else actual, o["responses"][code])
                media = (resp.get("content") or {}).get("application/json")
                return media.get("schema") if media else None
            cs, as_ = body(op), body(aop)
            if (cs is None) != (as_ is None):
                err(f"{label} {code}: JSON body presence differs")
            elif cs is not None:
                out = []
                diff_shape(shape(contract, cs), shape(actual, as_), f"{label} {code}", out)
                for line in out: err(line)
        if bool(op.get("requestBody")) != bool(aop.get("requestBody")):
            err(f"{label}: requestBody presence differs")
    for p in sorted(set(actual_paths) - contract_paths):
        if not p.startswith("/openapi"):
            err(f"{p}: route exists in the implementation but not in the contract")

# ----------------------------------------------------------------- hand-written webapp model
MODEL_SCHEMAS = ("Demand", "UserDemands")

def expected_ts_type(prop):
    """TypeScript type the hand-written model must use for a contract property."""
    if "$ref" in prop:
        name = prop["$ref"].rsplit("/", 1)[-1]
        return "string" if name == "DemandStatus" else name      # status stays wire-tolerant (MODEL-01)
    t = prop.get("type")
    if t in ("integer", "number"):
        return "number"
    if t == "string":
        return "string"
    if t == "array":
        return expected_ts_type(prop.get("items", {})) + "[]"
    return "?"

def check_model(contract, path):
    """Compare the hand-written src/models/demand.ts with the contract schemas."""
    if not Path(path).exists():
        print(f"NOTE: model file not found, skipped: {path}")
        return
    src = Path(path).read_text(encoding="utf-8")
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    schemas = (contract.get("components") or {}).get("schemas") or {}
    for name in MODEL_SCHEMAS:
        schema = schemas.get(name)
        if not schema:
            err(f"model: schema {name} is missing from the contract")
            continue
        m = re.search(r"export\s+interface\s+" + name + r"\s*\{(.*?)\n\}", src, flags=re.S)
        if not m:
            err(f"model: interface {name} not found in {path}")
            continue
        fields = {}
        for ln in m.group(1).split("\n"):
            ln = ln.split("//")[0].strip().rstrip(";")
            fm = re.match(r"^(\w+)(\?)?\s*:\s*(.+)$", ln)
            if fm:
                fields[fm.group(1)] = (bool(fm.group(2)), fm.group(3).strip())
        props, required = schema.get("properties", {}), set(schema.get("required", []))
        for f in sorted(set(props) - set(fields)):
            err(f"model: {name}.{f} is in the contract but missing from the model")
        for f in sorted(set(fields) - set(props)):
            err(f"model: {name}.{f} is in the model but not in the contract")
        for f, prop in props.items():
            if f not in fields:
                continue
            optional, ts = fields[f]
            if optional == (f in required):
                err(f"model: {name}.{f} is {'optional' if optional else 'required'} in the model but "
                    f"{'required' if f in required else 'optional'} in the contract")
            want = expected_ts_type(prop)
            if ts != want:
                err(f"model: {name}.{f} has type '{ts}', the contract implies '{want}'")
    enum = set((schemas.get("DemandStatus") or {}).get("enum", []))
    km = re.search(r"export\s+type\s+KnownDemandStatus\s*=\s*([^;\n]+)", src)
    if not km:
        err("model: type KnownDemandStatus not found")
    else:
        known = set(re.findall(r"['\"]([^'\"]+)['\"]", km.group(1)))
        if known != enum:
            err(f"model: KnownDemandStatus {sorted(known)} differs from the contract enum {sorted(enum)}")

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--contract", default="contracts/openapi.yaml")
    ap.add_argument("--actual", help="OpenAPI document generated by klesia-api (.json or .yaml)")
    ap.add_argument("--all", action="store_true", help="also compare operations marked 'adopted'")
    ap.add_argument("--model", help="hand-written webapp model (src/models/demand.ts) to compare with the contract")
    a = ap.parse_args()
    if not Path(a.contract).exists():
        sys.exit(f"contract not found: {a.contract} (run from the workspace root)")
    contract = load(a.contract)
    check_contract(contract)
    if a.actual:
        check_actual(contract, load(a.actual), a.all)
    if a.model:
        check_model(contract, a.model)
    for level, msg in findings:
        print(f"{level}: {msg}")
    n_err = sum(1 for l, _ in findings if l == "ERROR")
    ops = sum(1 for _ in operations(contract))
    print(f"\n{ops} operations checked, {n_err} error(s), {len(findings) - n_err} warning(s)")
    sys.exit(1 if n_err else 0)

if __name__ == "__main__":
    main()
